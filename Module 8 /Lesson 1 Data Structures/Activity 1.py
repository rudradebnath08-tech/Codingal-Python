fruits = ["apple", "mango", "cherry", "date", "elderberry"]

# Accessing items in the list
print(fruits[0])  # Output: apple
print(fruits[-1])  # Output: elderberry (last item, use -1)

# Finding the total number of items
print(len(fruits))  # Output: 5

# Slicing - getting the range of items
print(fruits[1:3])  # Output: ['mango', 'cherry']